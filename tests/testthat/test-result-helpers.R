test_that("response-to-events preserves content, state and token probabilities", {
  state <- continuation_state("openai", "test", data = json_object(value = "opaque"))
  message <- message_assistant(list(text("hi", continuation = list(state)), tool_call_part("c", "f", input = json_object(x = 1L))))
  message$continuation <- list(state)
  response <- response("model", message, "tool_call", id = "r", usage = usage(input_tokens = 2, output_tokens = 1), logprobs = list(token_logprob("hi", -0.1)))
  request <- request("model", list(message_user("hi")))
  restored <- materialize_response(response_to_events(response), request)
  expect_identical(as_json(restored), as_json(response))
  expect_error(response_to_events(response("model", message_assistant(refusal("no")), "stop")), class = "UnsupportedFeatureError")
})

test_that("fake models drive the real public complete and callback streaming APIs", {
  model <- fake_lm(c("first", "second"))
  request <- request("model", list(message_user("hi")))
  expect_identical(response_text(complete(model, request)), "first")
  events <- list()
  answer <- stream(model, request, function(event) events[[length(events) + 1L]] <<- event)
  expect_identical(response_text(answer), "second")
  expect_identical(vapply(events, function(event) event$type, ""), c("start", "delta", "end"))
  expect_length(recorded_requests(model), 2L)
  expect_error(complete(model, request), "no remaining")
})

test_that("fake HTTP transports retain error bytes and stream successful chunks", {
  transport <- fake_transport(list(list(status = 200L, chunks = list("a", "b")), list(status = 401L, body = "error")))
  wire <- list(method = "GET", url = "https://example.test", headers = list(), body = raw())
  seen <- character()
  first <- transport(wire, on_chunk = function(bytes) seen <<- c(seen, rawToChar(bytes)))
  expect_identical(seen, c("a", "b"))
  expect_identical(first$body, raw())
  second <- transport(wire, on_chunk = function(...) stop("must not emit error bytes"))
  expect_identical(rawToChar(second$body), "error")
  expect_length(recorded_requests(transport), 2L)
})
